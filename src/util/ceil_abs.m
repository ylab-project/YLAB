function v = ceil_abs(x, ndec)
%ceil_abs - 絶対値方向への切り上げ（SS7出力編A.9 応力表示の丸め）
%
%   v = ceil_abs(x, ndec) は、x を絶対値が大きくなる向きに小数
%   ndec 桁へ切り上げて返す。SS7 出力編 A.9「応力は切り上げ」に
%   従う表示用の丸め。符号は保持する。表示桁で 0 に丸まる微小値
%   （対称断面の理論 0 応力の数値ノイズ等）は 0 とし、切り上げに
%   よる過剰な ±1 表示を避ける。
%
%   入力引数:
%     x    - 丸め対象の数値（スカラーまたは配列）
%     ndec - 切り上げ後の小数桁数（0:整数, 1:小数1桁, ...）
%
%   出力引数:
%     v - 絶対値方向へ ndec 桁で切り上げた値（x と同サイズ）

f = 10 ^ ndec;
v = sign(x) .* ceil(abs(x) .* f) ./ f;
v(abs(x) < 0.5 / f) = 0;

return
end
